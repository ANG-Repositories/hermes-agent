@pytest.mark.parametrize("verb", ["launchd_start", "launchd_install", "refresh_launchd_plist_if_needed"])
def test_operator_daemon_refuses_definition_writers(monkeypatch, tmp_path, verb):
    from hermes_cli import gateway_launchd as ld
    daemon = "/Library/LaunchDaemons/ai.hermes.gateway.plist"
    monkeypatch.setattr(ld.Path, "is_file", lambda p: str(p) == daemon)
    monkeypatch.setattr(gateway_cli, "get_launchd_label", lambda: "ai.hermes.gateway")
    monkeypatch.setattr(gateway_cli, "get_launchd_plist_path", lambda: tmp_path / "missing.plist")
    monkeypatch.setattr(gateway_cli, "generate_launchd_plist", lambda: pytest.fail("must refuse before generating"))
    monkeypatch.setattr(ld.subprocess, "run", lambda *a, **kw: pytest.fail("must not bootstrap operator daemon"))
    with pytest.raises(SystemExit) as exc:
        getattr(gateway_cli, verb)()
    assert daemon in str(exc.value)
    assert "operator-owned" in str(exc.value)
    assert not (tmp_path / "missing.plist").exists()


def test_stale_plist_is_refreshed_before_any_kickstart(monkeypatch, launchd_seam):
    """The update-restart path must repair the definition, not revive a stale one."""
    refreshed = []
    monkeypatch.setattr(
        gateway_cli, "refresh_launchd_plist_if_needed", lambda: refreshed.append(1) or True
    )
    # Even when the kickstart later wedges (TimeoutExpired escapes to the
    # caller, exactly as on the broken host), the refresh must already have
    # run — that ordering is the contract.
    with pytest.raises(gateway_cli.subprocess.TimeoutExpired):
        gateway_cli.launchd_restart()

    assert refreshed == [1], "refresh must run before the restart decision"
    kickstarts = [c for c in launchd_seam if c[:2] == ["launchctl", "kickstart"]]
    assert kickstarts, "a current definition still needs the kickstart relaunch"


def test_failed_refresh_routes_to_bounded_bootstrap_not_the_90s_kickstart(monkeypatch, launchd_seam):
    """When the refresh couldn't re-register the job, kickstart would hang again.

    The bootstrap path (30s timeouts, loud failure) is the bounded revival.
    """
    monkeypatch.setattr(gateway_cli, "refresh_launchd_plist_if_needed", lambda: False)

    gateway_cli.launchd_restart()

    kickstarts = [c for c in launchd_seam if "kickstart" in c]
    assert not [c for c in kickstarts if "-k" in c], (
        "kickstart -k after a failed refresh is the exact 90s hang this guards against"
    )
    bootstraps = [c for c in launchd_seam if c[:2] == ["launchctl", "bootstrap"]]
    assert bootstraps, "the bounded bootstrap revival must run instead"


def test_protected_foreign_plist_skips_the_raw_bootstrap(monkeypatch, launchd_seam):
    """A refresh that deliberately left a foreign plist alone also returns False, but the job is still
    registered: a raw bootstrap would fail EIO and drop to a detached gateway. Use the kickstart path."""
    monkeypatch.delenv(gateway_cli._FOREIGN_SERVICE_OVERWRITE_ENV, raising=False)
    gateway_cli.get_launchd_plist_path().write_text(
        GENERATED_PLIST.replace("/usr/bin/osascript", "/opt/venv/bin/python"), encoding="utf-8"
    )
    monkeypatch.setattr(gateway_cli, "refresh_launchd_plist_if_needed", lambda: False)

    with pytest.raises(gateway_cli.subprocess.TimeoutExpired):
        gateway_cli.launchd_restart()

    assert not [c for c in launchd_seam if c[:2] == ["launchctl", "bootstrap"]]
    assert [c for c in launchd_seam if c[:2] == ["launchctl", "kickstart"] and "-k" in c]
